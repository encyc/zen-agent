"""Export a session as a self-contained Markdown or HTML document.

Read-only: the JSONL session is never modified. HTML is generated by hand with
``html.escape`` on every text node — model output is untrusted input, and an
exported transcript must never become executable markup.
"""

from __future__ import annotations

import html
import json
from pathlib import Path

from zenagent.agent.session import Session
from zenagent.types import (
    AssistantMessage,
    ImageContent,
    Message,
    SystemMessage,
    TextContent,
    ThinkingContent,
    ToolCall,
    ToolResultMessage,
    UserMessage,
)

__all__ = ["export_html", "export_markdown", "export_session"]

_HTML_STYLE = """
body{font-family:ui-monospace,SFMono-Regular,Menlo,monospace;max-width:52rem;
margin:2rem auto;padding:0 1rem;line-height:1.5;color:#1f2328}
h1{font-size:1.3rem;border-bottom:1px solid #d0d7de;padding-bottom:.4rem}
section{border-left:3px solid #d0d7de;padding-left:.8rem;margin:1rem 0}
section.user{border-color:#0969da}section.assistant{border-color:#1a7f37}
section.tool{border-color:#9a6700}section.system{border-color:#8250df}
section.error{border-color:#cf222e}section.error pre{color:#cf222e}
h2{font-size:.85rem;text-transform:uppercase;letter-spacing:.05em;color:#57606a;
margin:.2rem 0}
pre{background:#f6f8fa;padding:.6rem;overflow-x:auto;border-radius:4px}
details{color:#57606a}code{background:#f6f8fa;padding:0 .2rem}
"""


def _blocks(message: AssistantMessage):
    for block in message.content:
        if isinstance(block, TextContent):
            yield "text", block
        elif isinstance(block, ThinkingContent):
            yield "thinking", block
        elif isinstance(block, ToolCall):
            yield "tool", block


def export_markdown(messages: list[Message], *, title: str = "zenagent session") -> str:
    """Render the transcript as Markdown (thinking collapsed)."""
    lines = [f"# {title}", ""]
    for message in messages:
        if isinstance(message, SystemMessage):
            lines += ["## system", "", message.content, ""]
        elif isinstance(message, UserMessage):
            lines += ["## user", ""]
            if isinstance(message.content, str):
                lines += [message.content, ""]
            else:
                for block in message.content:
                    if isinstance(block, TextContent):
                        lines += [block.text, ""]
                    elif isinstance(block, ImageContent):
                        lines += [f"_[image {block.mime_type}]_", ""]
        elif isinstance(message, AssistantMessage):
            lines += ["## assistant", ""]
            for kind, block in _blocks(message):
                if kind == "text":
                    lines += [block.text, ""]
                elif kind == "thinking":
                    lines += [
                        "<details><summary>thinking</summary>",
                        "",
                        block.thinking,
                        "",
                        "</details>",
                        "",
                    ]
                else:
                    arguments = "{}" if block.arguments_error else block.arguments
                    lines += [
                        f"**tool call `{block.name}`**",
                        "",
                        "```json",
                        json.dumps(arguments, ensure_ascii=False, indent=2),
                        "```",
                        "",
                    ]
        elif isinstance(message, ToolResultMessage):
            marker = " ⚠️ error" if message.is_error else ""
            lines += [f"## tool result: {message.tool_name}{marker}", ""]
            for block in message.content:
                if isinstance(block, TextContent):
                    lines += ["```text", block.text, "```", ""]
                elif isinstance(block, ImageContent):
                    lines += [f"_[image {block.mime_type}]_", ""]
    return "\n".join(lines).rstrip() + "\n"


def export_html(messages: list[Message], *, title: str = "zenagent session") -> str:
    """Render the transcript as one self-contained, fully escaped HTML file."""
    escape = html.escape
    parts = [
        "<!doctype html>",
        '<html lang="en"><head><meta charset="utf-8">',
        f"<title>{escape(title)}</title>",
        f"<style>{_HTML_STYLE}</style></head><body>",
        f"<h1>{escape(title)}</h1>",
    ]

    def section(kind: str, heading: str, body: str) -> None:
        parts.append(f'<section class="{kind}"><h2>{escape(heading)}</h2>{body}</section>')

    for message in messages:
        if isinstance(message, SystemMessage):
            section("system", "system", f"<pre>{escape(message.content)}</pre>")
        elif isinstance(message, UserMessage):
            body = []
            if isinstance(message.content, str):
                body.append(f"<pre>{escape(message.content)}</pre>")
            else:
                for block in message.content:
                    if isinstance(block, TextContent):
                        body.append(f"<pre>{escape(block.text)}</pre>")
                    elif isinstance(block, ImageContent):
                        body.append(f"<p><em>[image {escape(block.mime_type)}]</em></p>")
            section("user", "user", "".join(body))
        elif isinstance(message, AssistantMessage):
            body = []
            for kind, block in _blocks(message):
                if kind == "text":
                    body.append(f"<pre>{escape(block.text)}</pre>")
                elif kind == "thinking":
                    body.append(
                        "<details><summary>thinking</summary>"
                        f"<pre>{escape(block.thinking)}</pre></details>"
                    )
                else:
                    arguments = "{}" if block.arguments_error else block.arguments
                    body.append(
                        f"<p><strong>tool call {escape(block.name)}</strong></p>"
                        f"<pre>{escape(json.dumps(arguments, ensure_ascii=False, indent=2))}</pre>"
                    )
            section("assistant", "assistant", "".join(body))
        elif isinstance(message, ToolResultMessage):
            css = "error" if message.is_error else "tool"
            heading = "tool result: " + message.tool_name + (" (error)" if message.is_error else "")
            body = []
            for block in message.content:
                if isinstance(block, TextContent):
                    body.append(f"<pre>{escape(block.text)}</pre>")
                elif isinstance(block, ImageContent):
                    body.append(f"<p><em>[image {escape(block.mime_type)}]</em></p>")
            section(css, heading, "".join(body))

    parts.append("</body></html>")
    return "\n".join(parts) + "\n"


def export_session(path: Path, fmt: str = "md", out: Path | None = None) -> Path:
    """Export ``path`` to Markdown or HTML; returns the written file."""
    session_path = Path(path)
    messages = Session(session_path).load()
    title = f"zenagent session · {session_path.name}"
    if fmt == "md":
        text = export_markdown(messages, title=title)
        suffix = ".md"
    elif fmt == "html":
        text = export_html(messages, title=title)
        suffix = ".html"
    else:
        raise ValueError(f"unknown export format {fmt!r} (use md or html)")
    target = Path(out) if out is not None else session_path.with_suffix(suffix)
    target.write_text(text, encoding="utf-8")
    return target
