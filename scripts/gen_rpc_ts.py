#!/usr/bin/env python3
"""Generate ``desktop/src/rpc/wire.gen.ts`` from the py wire registry.

``zenagent/cli/rpc/protocol.py`` is the single source of truth for the RPC
surface; this script renders its declarations as TypeScript. The output file
is a derivative: never edit it by hand, and never edit the shapes it mirrors
in ``desktop/src/rpc/types.ts`` — migrate those to re-exports domain by
domain. ``--check`` regenerates to a temp file and fails on any drift, which
is how ``scripts/check.sh`` keeps the two honest (a registry change without a
regeneration fails the gate, exactly like an unformatted file).

The generator only emits what ``OPS`` fully declares; ``PARTIAL`` stubs never
leak half-true types. Frontend-side refinements (discriminated unions over
the flat wire, e.g. ``WorkspaceFile``) stay handwritten in types.ts — the
generated flat interfaces are the wire truth they must stay compatible with.

Stdlib only, like check_architecture.py.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from zenagent.cli.rpc import protocol

TARGET = REPO / "desktop" / "src" / "rpc" / "wire.gen.ts"

_HEADER = """\
/** GENERATED by scripts/gen_rpc_ts.py from zenagent/cli/rpc/protocol.py —
 * do not edit. The registry is the wire's single source of truth; migrate
 * handwritten mirrors in types.ts to re-exports from here domain by domain.
 * Frontend refinements (unions narrowing the flat shapes) stay handwritten
 * and must stay compatible with these flat wire types. */
"""


def _ts_type(ty: object) -> str:
    if isinstance(ty, protocol.WireType):
        if ty.kind == "list":
            return f"Array<{_ts_type(ty.arg)}>"
        if ty.kind == "record":
            return f"Record<string, {_ts_type(ty.arg)}>"
        if ty.kind == "ref":
            return protocol.SHAPES[ty.arg]["ts"]  # validate_registry guards this
        if ty.kind == "enum":
            return " | ".join(f"'{value}'" for value in ty.arg)
    scalar = {
        protocol.STRING: "string",
        protocol.INT: "number",
        protocol.FLOAT: "number",
        protocol.BOOL: "boolean",
        protocol.BOOL_LAX: "boolean",
        protocol.STRING_LAX: "string",
        protocol.NUMBER_LAX: "number | string",
        protocol.ANY: "unknown",
    }.get(ty)
    if scalar is None:
        raise SystemExit(f"unmapped field type: {ty!r}")
    return scalar


def _render_fields(fields: dict[str, protocol.Field], *, request: bool) -> list[str]:
    """Interface body lines. Result side: ``optional`` → ``?:``, ``nullable``
    → ``| null``. Request side: ``required`` → plain, the rest → ``?:``."""
    lines: list[str] = []
    for name, field in fields.items():
        ts = _ts_type(field.ty)
        note = ""
        if field.ty == protocol.BOOL_LAX:
            note = " /** junk tolerated server-side (treated as false). */"
        if field.ty == protocol.STRING_LAX:
            note = " /** junk tolerated server-side (default applied). */"
        if request:
            suffix = "" if field.required else "?"
            lines.append(f"  {name}{suffix}: {ts}{note}")
        else:
            suffix = "?" if field.optional else ""
            null = " | null" if field.nullable else ""
            lines.append(f"  {name}{suffix}: {ts}{null}{note}")
    return lines


def _shape_blocks() -> list[str]:
    blocks: list[str] = []
    for entry in protocol.SHAPES.values():
        doc = entry["doc"]
        body = "\n".join(_render_fields(entry["fields"], request=False))
        header = f"export interface {entry['ts']} {{"
        if doc:
            blocks.append(f"/** {doc} */\n{header}\n{body}\n}}")
        else:
            blocks.append(f"{header}\n{body}\n}}")
    return blocks


def _request_block(kind: str, spec: protocol.OpSpec) -> str | None:
    """One request interface per fully-declared op; None when fieldless."""
    if not spec.request.FIELDS:
        return None
    body = "\n".join(_render_fields(spec.request.FIELDS, request=True))
    return f"export interface {_camel(kind, 'Request')} {{\n{body}\n}}"


def _result_block(kind: str, spec: protocol.OpSpec) -> str:
    body = "\n".join(
        _render_fields(spec.result, request=False)
    )
    ok = "boolean" if spec.ok_mutable else "true"
    return f"export interface {_camel(kind, 'Result')} {{\n  type: 'result'\n  id: string\n  ok: {ok}\n{body}\n}}"


def _sub_op_blocks(kind: str) -> list[str]:
    """A sub-op family (memory, session): one request per `op`, a
    discriminated request union, and one result envelope per sub (each named
    for its own consumers)."""
    spec = protocol.OPS[kind]
    subs = spec.subs or {}
    blocks: list[str] = []
    members: list[str] = []
    for sub_name, sub in subs.items():
        fields = {"op": protocol.Field(protocol.STRING, required=True), **sub.request.FIELDS}
        body = "\n".join(_render_fields(fields, request=True))
        blocks.append(
            f"export interface {_camel(kind, sub_name, 'Request')} {{\n{body}\n}}"
        )
        members.append(_camel(kind, sub_name, "Request"))
        payload = "\n".join(_render_fields(sub.result, request=False))
        ok = "boolean" if sub.ok_mutable else "true"
        blocks.append(
            f"export interface {_camel(kind, sub_name, 'Result')} {{\n"
            f"  type: 'result'\n  id: string\n  ok: {ok}\n{payload}\n}}"
        )
    blocks.append(f"export type {_camel(kind, 'Request')} =\n  | " + "\n  | ".join(members))
    return blocks


def _event_blocks() -> list[str]:
    types = " | ".join(f"'{name}'" for name in protocol.EVENT_TYPES)
    body = "\n".join(_render_fields(protocol.EVENT_FIELDS, request=False))
    return [
        f"export type AgentEventType = {types}",
        (
            "/** The flat wire truth of `codec.serialize_event`: `type` discriminates,\n"
            " * every other key is conditional on it. Handwritten per-event unions in\n"
            " * types-events.ts refine this and must stay assignable to it. */\n"
            f"export interface AgentEventWire {{\n{body}\n}}"
        ),
    ]


def _camel(*parts: str) -> str:
    """Snake-to-Pascal across all parts: ('fs_list', 'Result') -> FsListResult."""
    words: list[str] = []
    for part in parts:
        words.extend(part.split("_"))
    return "".join(word[:1].upper() + word[1:] for word in words)


def generate() -> str:
    sections: list[str] = [_HEADER]
    sections.append("// ---- result shapes -------------------------------------------------------\n")
    sections.extend(_shape_blocks())
    sections.append("\n// ---- op requests ---------------------------------------------------------\n")
    for kind, spec in protocol.OPS.items():
        if spec.subs is not None:
            continue
        block = _request_block(kind, spec)
        if block:
            sections.append(block)
    sections.append("\n// ---- op results ----------------------------------------------------------\n")
    for kind, spec in protocol.OPS.items():
        if spec.subs is not None:
            continue
        sections.append(_result_block(kind, spec))
    for sub_kind in (name for name, spec in protocol.OPS.items() if spec.subs):
        sections.append(f"\n// ---- {sub_kind} (sub-op family) ---------------------------------------------\n")
        sections.extend(_sub_op_blocks(sub_kind))
    sections.append("\n// ---- events (flat wire truth) ---------------------------------------------\n")
    sections.extend(_event_blocks())
    return "\n\n".join(sections) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate to a temp file and fail on drift instead of writing",
    )
    args = parser.parse_args()
    output = generate()
    if args.check:
        with tempfile.NamedTemporaryFile("w", suffix=".ts", delete=False) as handle:
            handle.write(output)
            temp = Path(handle.name)
        try:
            same = temp.read_text(encoding="utf-8") == (
                TARGET.read_text(encoding="utf-8") if TARGET.is_file() else None
            )
        finally:
            temp.unlink()
        if not same:
            print(f"wire.gen.ts is stale: regenerate with {Path(__file__).name}")
            return 1
        print("wire.gen.ts is fresh")
        return 0
    TARGET.write_text(output, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)} ({len(output.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
